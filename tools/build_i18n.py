def build_catalog():
    catalog = {}
    for zh in EN:
        catalog[zh] = {'en-US': EN[zh], 'zh-CN': zh, 'zh-TW': ZH_TW.get(zh, zh), 'ja-JP': JA.get(zh, zh)}
    for locale in OTHERS:
        over = OVERRIDES.get(locale, {})
        for zh in EN:
            catalog.setdefault(zh, {})[locale] = over.get(zh, EN[zh])
    es = TR['es-ES']
    for zh in EN:
        catalog[zh]['es-ES'] = es.get(zh, EN[zh])
    # zh-TW entries defined but missing default to zh-CN mapping (already set)
    for key in RETIRED_KEYS:
        catalog.pop(key, None)
    return catalog

def po_escape(text):
    return text.replace('\\', '\\\\').replace('"', '\\"')

def write_po(path, entries):
    lines = []
    for msgid, msgstr in entries:
        lines.append('msgid "%s"' % po_escape(msgid))
        lines.append('msgstr "%s"' % po_escape(msgstr))
        lines.append('')
    with io.open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines))

def main():
    catalog = build_catalog()
    code_msgids = set()
    # app-widget（快捷卡片）也要扫：它的文案同样走 t()，只扫 page/ 会让卡片新增
    # 词条静默漏掉全部 34 种语言（缺译时 on device 直接显示中文原文）。
    scan_roots = [os.path.join(ROOT, 'page'), os.path.join(ROOT, 'app-widget')]
    for scan_root in scan_roots:
        if not os.path.isdir(scan_root):
            continue
        for root_dir, _dirs, files in os.walk(scan_root):
            if os.sep + 'i18n' in root_dir:
                continue
            for name in files:
                # 设备端源码是 .ts；app-widget/index.js 仍是 .js。
                if name.endswith('.ts') or name.endswith('.js'):
                    src = io.open(os.path.join(root_dir, name), encoding='utf-8').read()
                    code_msgids |= set(re.findall(r"\btf?\('((?:[^'\\]|\\.)*)'\s*[,)]", src))
    missing = sorted(code_msgids - set(catalog))
    if missing:
        print('MISSING in catalog:')
        for item in missing:
            print('  %r' % item)
        sys.exit(1)
    os.makedirs(OUT, exist_ok=True)
    locales = sorted(set(LOCALES))
    for locale in locales:
        entries = []
        for zh in sorted(catalog):
            msgstr = catalog[zh].get(locale)
            if msgstr is None:
                print('missing %s translation: %r' % (locale, zh))
                sys.exit(1)
            entries.append((zh, msgstr))
        write_po(os.path.join(OUT, locale + '.po'), entries)
        print('%s.po: %d entries' % (locale, len(entries)))
    # po catalogs are the single translation source. zeus compiles them into
    # assets/raw/locale/*.btxt for @zos/i18n getText. A JS mirror of the whole
    # catalog (utils/i18n-data.js) used to be generated here as a fallback; it
    # was removed because it duplicated the same strings into the device heap
    # (38% of all device-side JS) for no behavioural gain.
    stale = os.path.join(ROOT, 'utils', 'i18n-data.js')
    if os.path.exists(stale):
        os.remove(stale)
        print('removed obsolete i18n-data.js')

    # drop obsolete po files not in the locale list
    for name in os.listdir(OUT):
        if name.endswith('.po') and name[:-3] not in locales:
            os.remove(os.path.join(OUT, name))
            print('removed obsolete %s' % name)

if __name__ == '__main__':
    main()
